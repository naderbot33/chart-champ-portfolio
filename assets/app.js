  // Lazy-load the TradingView library only when a ready chart is actually opened.
  var TV_SRC = "https://s3.tradingview.com/tv.js";
  var tvState = 0; // 0 idle, 1 loading, 2 ready, -1 failed
  var tvWaiters = [];
  function tvFlush(ok) {
    var q = tvWaiters.slice();
    tvWaiters.length = 0;
    q.forEach(function (cb) { cb(ok); });
  }
  function loadTradingView(cb) {
    if (window.TradingView && typeof window.TradingView.widget === "function") { cb(true); return; }
    tvWaiters.push(cb);
    if (tvState === 1) return;
    if (tvState === -1) { tvFlush(false); return; }
    tvState = 1;
    var s = document.createElement("script");
    s.src = TV_SRC;
    s.async = true;
    s.onload = function () { tvState = 2; tvFlush(true); };
    s.onerror = function () { tvState = -1; tvFlush(false); };
    document.head.appendChild(s);
  }

